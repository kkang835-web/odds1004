export function normalizeTeamKey(name: string): string {
  return String(name || "")
    .toLowerCase()
    .replace(/\([^)]*\)/g, "")
    .replace(/\bfc\b|\bsc\b|\bcf\b|\bafc\b/gi, "")
    .replace(/[\s.\-_'"`]/g, "")
    .trim();
}

export function translateTeamNameToEnglish(teamName: string): string {
  if (!teamName) return "";
  const trimmed = teamName.trim();
  if (TEAM_TRANSLATIONS[trimmed]) {
    return TEAM_TRANSLATIONS[trimmed];
  }

  const noSpace = trimmed.replace(/\s+/g, "");
  if (TEAM_TRANSLATIONS[noSpace]) {
    return TEAM_TRANSLATIONS[noSpace];
  }

  // Prefer longest matching Korean key to avoid short collisions (e.g. "올랜" vs "올랜시티" vs "올랜매직")
  const sortedEntries = Object.entries(TEAM_TRANSLATIONS).sort((a, b) => b[0].length - a[0].length);
  for (const [key, val] of sortedEntries) {
    if (trimmed.includes(key) || noSpace.includes(key.replace(/\s+/g, ""))) {
      return val;
    }
  }

  return trimmed;
}

